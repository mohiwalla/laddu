/**
 * The containers' Codex config.toml. No model provider of its own: Codex calls OpenAI with the
 * person's own ChatGPT login, kept in auth.json in their CODEX_HOME (see account.ts).
 */
export function codexConfig({
	desktop,
}: {
	/** Path (as Codex sees it) to runtime/desktop, whose `mcp` mode gives Codex its computer. */
	desktop?: string
}) {
	return `# Generated by apps/api on startup; edits are overwritten.
# Sign-ins are ChatGPT accounts only, kept in CODEX_HOME/auth.json (containers have no keyring).
forced_login_method = "chatgpt"
cli_auth_credentials_store = "file"
# OpenAI's hosted web search, run inside the model call.
web_search = "live"
# Readable reasoning in the session logs, so a turn that stops early can be traced.
model_reasoning_summary = "concise"
${
	desktop
		? `
# laddu's computer: a desktop in the container, driven by screenshots, the accessibility tree and
# real mouse and keyboard input. Started on first use; see runtime/desktop.
[mcp_servers.desktop]
command = "${desktop}"
args = ["mcp"]
startup_timeout_sec = 30
tool_timeout_sec = 90
`
		: ""
}`
}
