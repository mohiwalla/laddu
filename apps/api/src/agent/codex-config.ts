import { RESOURCE } from "../auth/siwc"

/**
 * Codex config.toml billing the owner's ChatGPT plan (SIWC).
 * Host runtime: straight to OpenAI with ACCESS_TOKEN. Docker runtime: via the model proxy,
 * authenticated with DOT_PROXY_KEY, so the real token never enters a container.
 */
export function codexConfig({
	baseUrl = RESOURCE,
	envKey = "ACCESS_TOKEN",
	modelCatalog,
}: {
	baseUrl?: string
	envKey?: string
	/** Path (as Codex sees it) to the catalog from writeModelCatalog(). */
	modelCatalog: string
}) {
	return `# Generated by apps/api on startup; edits are overwritten.
model_provider = "openai_chatgpt_plan"
# Codex's own model catalog with sub-agents switched off (see writeModelCatalog in containers.ts).
model_catalog_json = "${modelCatalog}"

[model_providers.openai_chatgpt_plan]
name = "ChatGPT plan"
base_url = "${baseUrl}"
env_key = "${envKey}"
wire_api = "responses"
requires_openai_auth = false
supports_websockets = false

[features]
# Sub-agent replies come back as agent_message input items, which plan usage rejects
# (subscription_sharing_unsupported_capability) and which then poison the thread. Newer models
# turn sub-agents on from their catalog entry regardless of this; the catalog above covers them.
multi_agent = false

# Image generation isn't available on the plan route, so the built-in skill would only fail.
[[skills.config]]
name = "imagegen"
enabled = false
`
}
